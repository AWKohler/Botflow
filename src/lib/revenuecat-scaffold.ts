/**
 * RevenueCat scaffolding — the Convex files we drop into a project the first time
 * RevenueCat is connected, plus the env vars they read. Mirrors stripe-scaffold.ts.
 *
 *   convex/revenueCatWebhook.ts  (read-only) — verifies the platform's V2 HMAC
 *                                signature + freshness, then hands off to billing.
 *   convex/revenueCatBilling.ts  (editable)  — the app's entitlement logic.
 *
 * Env vars set on the project's Convex deployment:
 *   BOTFLOW_PROJECT_ID
 *   BOTFLOW_REVENUECAT_WEBHOOK_SECRET  (the per-project HMAC the receiver verifies)
 */
import { eq } from 'drizzle-orm';
import { getDb } from '@/db';
import { projects } from '@/db/schema';
import { sandboxWriteFile } from '@/lib/vercel-sandbox';

export const REVENUECAT_WEBHOOK_TS = `// AUTO-GENERATED by Botflow. Do not edit — the agent's write-guard will refuse changes.
//
// Convex HTTP endpoint that receives normalized RevenueCat entitlement events
// forwarded by the Botflow platform. Verifies the timestamped HMAC signature
// (so randoms can't spoof or replay events), then hands off to
// revenueCatBilling.ts (which IS editable — that's where you grant/revoke).
//
// Wire it up in convex/http.ts:
//   import { revenueCatWebhook } from "./revenueCatWebhook";
//   http.route({ path: "/revenuecat/webhook", method: "POST", handler: revenueCatWebhook });
import { httpAction } from "./_generated/server";
import { internal } from "./_generated/api";

const PROJECT_SECRET = process.env.BOTFLOW_REVENUECAT_WEBHOOK_SECRET;

async function hmacHex(secret: string, message: string): Promise<string> {
  const enc = new TextEncoder();
  const key = await crypto.subtle.importKey(
    "raw",
    enc.encode(secret),
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"],
  );
  const sig = await crypto.subtle.sign("HMAC", key, enc.encode(message));
  return Array.from(new Uint8Array(sig))
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

function safeEqual(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let mismatch = 0;
  for (let i = 0; i < a.length; i++) mismatch |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return mismatch === 0;
}

export const revenueCatWebhook = httpAction(async (ctx, req) => {
  if (!PROJECT_SECRET) {
    return new Response("RevenueCat integration not configured", { status: 500 });
  }
  const raw = await req.text();

  // Require the timestamped V2 signature: HMAC("<timestamp>.<body>") within 5
  // minutes. Binding a fresh timestamp blocks replay of a captured request.
  const tsHeader = req.headers.get("X-Botflow-Timestamp");
  const sigV2 = req.headers.get("X-Botflow-Signature-V2");
  if (!tsHeader || !sigV2) {
    return new Response("missing signature", { status: 401 });
  }
  const ts = Number(tsHeader);
  const nowSec = Math.floor(Date.now() / 1000);
  if (!Number.isFinite(ts) || Math.abs(nowSec - ts) > 300) {
    return new Response("stale or invalid timestamp", { status: 401 });
  }
  const expected = await hmacHex(PROJECT_SECRET, ts + "." + raw);
  if (!safeEqual(sigV2, expected)) {
    return new Response("bad signature", { status: 401 });
  }

  let event: { type: string; id: string; data?: unknown };
  try {
    event = JSON.parse(raw);
  } catch {
    return new Response("invalid json", { status: 400 });
  }

  await ctx.runMutation(internal.revenueCatBilling.applyRevenueCatEvent, { event });
  return new Response("ok", { status: 200 });
});
`;

