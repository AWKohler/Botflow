// ───────────────────────── http.ts wiring ──────────────────────────

const HTTP_TS_FRESH = `// AUTO-GENERATED by Botflow.
import { httpRouter } from "convex/server";
import { revenueCatWebhook } from "./revenueCatWebhook";

const http = httpRouter();

http.route({ path: "/revenuecat/webhook", method: "POST", handler: revenueCatWebhook });

export default http;
`;

const ROUTE_IMPORT = `import { revenueCatWebhook } from "./revenueCatWebhook";`;
const ROUTE_LINE = `http.route({ path: "/revenuecat/webhook", method: "POST", handler: revenueCatWebhook });`;

/**
 * Ensure /convex/http.ts routes POST /revenuecat/webhook → revenueCatWebhook.
 * - Missing file → write a complete one.
 * - Present, already wired → leave it.
 * - Present, not wired → inject the import + route line (best-effort). If the
 *   expected `export default http` anchor isn't found, leave the file untouched
 *   and rely on the agent (the prompt instructs it) rather than risk corruption.
 *
 * Returns a short status for logging. Never throws.
 */
export async function ensureRevenueCatHttpRoute(
  projectId: string,
): Promise<'created' | 'already' | 'injected' | 'manual'> {
  const existing = await sandboxReadFile(projectId, '/convex/http.ts').catch(() => null);
  if (!existing || !existing.content) {
    await sandboxWriteFile(projectId, '/convex/http.ts', HTTP_TS_FRESH);
    return 'created';
  }
  const src = existing.content;
  if (src.includes('revenueCatWebhook')) return 'already';

  // Inject the route before `export default http`.
  const anchorMatch = src.match(/export\s+default\s+http\s*;?/);
  if (!anchorMatch) return 'manual'; // unfamiliar shape — don't risk it

  const importBlock = src.includes(ROUTE_IMPORT) ? '' : `${ROUTE_IMPORT}\n`;
  const withImport = importBlock
    // Put the import after the last existing import line for tidiness; fall back
    // to prepending if no import lines exist.
    ? (() => {
        const importLines = [...src.matchAll(/^import .*$/gm)];
        if (importLines.length === 0) return importBlock + src;
        const last = importLines[importLines.length - 1];
        const idx = (last.index ?? 0) + last[0].length;
        return src.slice(0, idx) + `\n${ROUTE_IMPORT}` + src.slice(idx);
      })()
    : src;

  const injected = withImport.replace(
    anchorMatch[0],
    `${ROUTE_LINE}\n\n${anchorMatch[0]}`,
  );
  await sandboxWriteFile(projectId, '/convex/http.ts', injected);
  return 'injected';
}

// ───────────────────────── apply to sandbox ──────────────────────────

/**
 * Drop the RevenueCat Convex files into the project's sandbox. Idempotent —
 * revenueCatWebhook.ts is always overwritten (read-only by intent); billing.ts
 * is only created if missing (the agent edits it); http.ts is ensured.
 *
 * Returns the list of paths written + the http.ts wiring status.
 */
export async function dropRevenueCatFilesIntoSandbox(
  projectId: string,
): Promise<{ written: string[]; httpStatus: string }> {
  const written: string[] = [];

  await sandboxWriteFile(projectId, '/convex/revenueCatWebhook.ts', REVENUECAT_WEBHOOK_TS);
  written.push('/convex/revenueCatWebhook.ts');

  // Only seed billing.ts if missing — the agent owns this file.
  const existing = await sandboxReadFile(projectId, '/convex/billing.ts').catch(() => null);
  if (!existing || !existing.content) {
    await sandboxWriteFile(projectId, '/convex/billing.ts', BILLING_TS);
    written.push('/convex/billing.ts');
  }

  const httpStatus = await ensureRevenueCatHttpRoute(projectId);
  if (httpStatus === 'created' || httpStatus === 'injected') {
    written.push('/convex/http.ts');
  }

  return { written, httpStatus };
}

/** Promise.race-with-timeout, never throws. */
function withTimeout<T>(p: Promise<T>, ms: number, label: string): Promise<T> {
  return Promise.race([
    p,
    new Promise<T>((_, rej) => setTimeout(() => rej(new Error(`${label} timed out after ${ms}ms`)), ms)),
  ]);
}

/**
 * Set the Convex env vars the scaffolded files read. Mirrors setStripeConvexEnv.
 */
export async function setRevenueCatConvexEnv(
  projectId: string,
  opts: { webhookSecret: string; proxyBase?: string; environment?: string },
): Promise<{ ok: true } | { ok: false; error: string }> {
  const db = getDb();
  const [project] = await db.select().from(projects).where(eq(projects.id, projectId));
  if (!project) return { ok: false, error: 'Project not found' };

  const deployUrl = project.backendType === 'user' ? project.userConvexUrl : project.convexDeployUrl;
  const deployKey = project.backendType === 'user' ? project.userConvexDeployKey : project.convexDeployKey;
  if (!deployUrl || !deployKey) {
    return { ok: false, error: 'Convex deployment is not configured for this project' };
  }

  const vars = {
    BOTFLOW_PROJECT_ID: projectId,
    BOTFLOW_REVENUECAT_PROXY_BASE: opts.proxyBase ?? 'https://botflow.io',
    BOTFLOW_REVENUECAT_WEBHOOK_SECRET: opts.webhookSecret,
    REVENUECAT_ENVIRONMENT: opts.environment ?? 'sandbox',
  };
  const changes = Object.entries(vars).map(([name, value]) => ({ name, value }));
  const res = await fetch(`${deployUrl}/api/update_environment_variables`, {
    method: 'POST',
    headers: { Authorization: `Convex ${deployKey}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ changes }),
  });
  if (!res.ok) {
    const text = await res.text();
    return { ok: false, error: `Failed to set Convex env (${res.status}): ${text.slice(0, 300)}` };
  }
  return { ok: true };
}

/**
 * One-call helper: drop the files AND set the env vars. The connect / initialize
 * endpoints call this after RevenueCat becomes connected. Failures are logged
 * but non-fatal.
 */
export async function scaffoldRevenueCatIntoProject(
  projectId: string,
  opts: { webhookSecret: string; proxyBase?: string; environment?: string },
): Promise<{
  filesWritten: string[];
  httpStatus?: string;
  envSet: boolean;
  envError?: string;
  filesError?: string;
}> {
  let filesWritten: string[] = [];
  let httpStatus: string | undefined;
  let filesError: string | undefined;
  try {
    const result = await withTimeout(
      dropRevenueCatFilesIntoSandbox(projectId),
      15_000,
      'dropRevenueCatFilesIntoSandbox',
    );
    filesWritten = result.written;
    httpStatus = result.httpStatus;
  } catch (err) {
    filesError = err instanceof Error ? err.message : String(err);
    console.error('[revenuecat-scaffold] file drop failed:', err);
  }

  const envResult = await withTimeout(
    setRevenueCatConvexEnv(projectId, opts),
    10_000,
    'setRevenueCatConvexEnv',
  ).catch((err) => ({
    ok: false as const,
    error: err instanceof Error ? err.message : String(err),
  }));

  return {
    filesWritten,
    ...(httpStatus ? { httpStatus } : {}),
    envSet: envResult.ok === true,
    ...(envResult.ok === true ? {} : { envError: envResult.error }),
    ...(filesError ? { filesError } : {}),
  };
}
