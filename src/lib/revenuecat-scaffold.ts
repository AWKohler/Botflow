/**
 * RevenueCat scaffolding — the Convex files we drop into a Swift+Convex project's
 * sandbox once RevenueCat is connected (or already-connected).
 *
 * Mirrors stripe-scaffold.ts, but for the iOS in-app-purchase flow:
 *   /convex/revenueCatWebhook.ts  — read-only httpAction; verifies the platform
 *       HMAC and hands off to billing.ts. (Receives entitlement events forwarded
 *       by /api/webhooks/revenuecat.)
 *   /convex/billing.ts            — EDITABLE; where the agent reacts to events
 *       (e.g. mirror subscription state into a Convex table for server logic).
 *   /convex/http.ts               — ensured to route POST /revenuecat/webhook.
 *
 * Plus Convex env vars the webhook file reads:
 *   BOTFLOW_PROJECT_ID
 *   BOTFLOW_REVENUECAT_PROXY_BASE
 *   BOTFLOW_REVENUECAT_WEBHOOK_SECRET
 *   REVENUECAT_ENVIRONMENT
 *
 * Unlike Stripe, entitlement checks happen on-device via the RevenueCat SDK, so
 * there's no outbound platform proxy file to scaffold — Convex only RECEIVES.
 */
