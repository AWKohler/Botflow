/** Set the Convex env vars the scaffolded RevenueCat receiver reads. Idempotent. */
export async function setRevenueCatConvexEnv(
  projectId: string,
): Promise<{ ok: true } | { ok: false; error: string }> {
  const db = getDb();
  const [project] = await db.select().from(projects).where(eq(projects.id, projectId));
  if (!project) return { ok: false, error: 'Project not found' };
  if (!project.revenuecatWebhookSecret) {
    return { ok: false, error: 'Project has no RevenueCat webhook secret' };
  }

  const deployUrl = project.backendType === 'user' ? project.userConvexUrl : project.convexDeployUrl;
  const deployKey = project.backendType === 'user' ? project.userConvexDeployKey : project.convexDeployKey;
  if (!deployUrl || !deployKey) {
    return { ok: false, error: 'Convex deployment is not configured for this project' };
  }

  const vars = {
    BOTFLOW_PROJECT_ID: projectId,
    BOTFLOW_REVENUECAT_WEBHOOK_SECRET: project.revenuecatWebhookSecret,
  };
  const changes = Object.entries(vars).map(([name, value]) => ({ name, value }));
  const res = await fetch(`${deployUrl}/api/update_environment_variables`, {
    method: 'POST',
    headers: { Authorization: `Convex ${deployKey}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ changes }),
  });
  if (!res.ok) {
    // Don't echo the upstream body — the payload carries the secret.
    await res.text().catch(() => '');
    return { ok: false, error: `Failed to set Convex env (status ${res.status})` };
  }
  return { ok: true };
}

/**
 * Inject the /revenuecat/webhook route into an existing convex/http.ts so the
 * platform's signed deliveries actually reach the receiver (otherwise they 404
 * before verification). Returns the updated source, or null if already wired /
 * shape unrecognized (the agent guidance covers that fallback).
 */
export function wireRevenueCatRoute(httpSrc: string): string | null {
  if (httpSrc.includes('/revenuecat/webhook')) return null; // already wired
  // Only touch a genuine Convex http router file.
  if (!/httpRouter\s*\(/.test(httpSrc)) return null;
  const exportMatch = httpSrc.match(/export\s+default\s+(\w+)\s*;?/);
  if (!exportMatch) return null;
  const routerVar = exportMatch[1];
  // The exported identifier must actually be the httpRouter() instance, or we'd
  // inject `<word>.route(...)` against something that isn't a router.
  const routerDecl = new RegExp(`(?:const|let|var)\\s+${routerVar}\\s*=\\s*httpRouter\\s*\\(`);
  if (!routerDecl.test(httpSrc)) return null;

  let src = httpSrc;
  // Detect an existing import regardless of quote style before adding one.
  if (!/from\s+["']\.\/revenueCatWebhook["']/.test(src)) {
    const importLine = 'import { revenueCatWebhook } from "./revenueCatWebhook";';
    const lastImport = src.lastIndexOf('\nimport ');
    if (lastImport >= 0) {
      const eol = src.indexOf('\n', lastImport + 1);
      src = src.slice(0, eol + 1) + importLine + '\n' + src.slice(eol + 1);
    } else {
      src = importLine + '\n' + src;
    }
  }
  const routeLine = `${routerVar}.route({ path: "/revenuecat/webhook", method: "POST", handler: revenueCatWebhook });`;
  src = src.replace(exportMatch[0], `${routeLine}\n\n${exportMatch[0]}`);
  return src;
}

/** Drop the receiver/billing files into the project's /convex and set env vars. */
export async function scaffoldRevenueCatIntoProject(projectId: string): Promise<{
  filesWritten: string[];
  envSet: boolean;
  routeWired: boolean;
  envError?: string;
  filesError?: string;
}> {
  const { sandboxReadFile } = await import('@/lib/vercel-sandbox');
  const written: string[] = [];
  let filesError: string | undefined;
  let routeWired = false;
  try {
    // Always re-write the read-only receiver.
    await sandboxWriteFile(projectId, '/convex/revenueCatWebhook.ts', REVENUECAT_WEBHOOK_TS);
    written.push('/convex/revenueCatWebhook.ts');
    // Only seed billing if missing — the agent owns it.
    const existing = await sandboxReadFile(projectId, '/convex/revenueCatBilling.ts').catch(() => null);
    if (!existing || !existing.content) {
      await sandboxWriteFile(projectId, '/convex/revenueCatBilling.ts', REVENUECAT_BILLING_TS);
      written.push('/convex/revenueCatBilling.ts');
    }
    // Mount the route in convex/http.ts so deliveries don't 404. If http.ts
    // doesn't exist yet (no auth set up), the agent wires it per guidance.
    const http = await sandboxReadFile(projectId, '/convex/http.ts').catch(() => null);
    if (http && http.content) {
      const updated = wireRevenueCatRoute(http.content);
      if (updated) {
        await sandboxWriteFile(projectId, '/convex/http.ts', updated);
        written.push('/convex/http.ts');
        routeWired = true;
      } else if (http.content.includes('/revenuecat/webhook')) {
        routeWired = true; // already mounted
      }
    }
  } catch (err) {
    filesError = err instanceof Error ? err.message : String(err);
    console.error('[revenuecat-scaffold] file drop failed:', err);
  }

  const envResult = await setRevenueCatConvexEnv(projectId).catch((err) => ({
    ok: false as const,
    error: err instanceof Error ? err.message : String(err),
  }));

  return {
    filesWritten: written,
    envSet: envResult.ok === true,
    routeWired,
    ...(envResult.ok === true ? {} : { envError: envResult.error }),
    ...(filesError ? { filesError } : {}),
  };
}
