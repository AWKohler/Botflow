#!/usr/bin/env bash
# Packs scripts/sim-demo-app (the "Botflow host check" SwiftUI app) into the
# tarball the admin panel's simulator test uploads, and writes it as base64 to
# src/lib/sim-hosts/demo-app.generated.ts. Run after changing the demo app.
# Needs XcodeGen (brew install xcodegen). macOS only.
set -euo pipefail
cd "$(dirname "$0")/.."
src=scripts/sim-demo-app
out=src/lib/sim-hosts/demo-app.generated.ts
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

cp -R "$src"/. "$work/"
# Ship a generated .xcodeproj too: hosts regenerate it from project.yml when
# they have XcodeGen, and build the shipped one when they don't.
(cd "$work" && xcodegen generate --quiet)
# No AppleDouble (._*) files or extended attributes in the archive.
COPYFILE_DISABLE=1 tar --no-xattrs --exclude='.DS_Store' -czf "$work.tgz" -C "$work" .
b64="$(base64 < "$work.tgz" | tr -d '\n')"
bytes="$(wc -c < "$work.tgz" | tr -d ' ')"
rm -f "$work.tgz"

{
  echo "// Generated by scripts/build-sim-demo-app.sh from scripts/sim-demo-app. Do not edit."
  echo "// The \"Botflow host check\" app (tar.gz, ${bytes} bytes) used by the admin panel's simulator test."
  echo "export const SIM_DEMO_APP_SCHEME = \"HostCheck\";"
  echo "export const SIM_DEMO_APP_BUNDLE_ID = \"com.botflow.hostcheck\";"
  echo "export const SIM_DEMO_APP_TGZ_BASE64 ="
  echo "  \"${b64}\";"
} > "$out"
echo "wrote $out (${bytes} bytes tar.gz)"
